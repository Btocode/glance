#!/usr/bin/env python3
"""Generate rust/glance_core/src/privacy/tables.rs: the character classes Python's `re` and
`str` methods use in glance.privacy, so the Rust twin matches them code point for code point.

    .venv/bin/python scripts/gen-privacy-tables.py

Run it with the Python CI tests on (the oldest supported, 3.10): the tables carry that
Python's Unicode version, and the parity test compares against it.
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "rust/glance_core/src/privacy/tables.rs"
MAX = sys.maxunicode + 1
KEYWORD_LETTERS = sorted(set("passwordpasswdpwdsecrettokenapikey"))


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # never in a Rust str
        if pred(chr(cp)):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def decimal_runs() -> list[tuple[int, int, int]]:
    """(first, last, value of first) for runs of consecutive decimal digits."""
    out: list[tuple[int, int, int]] = []
    for cp in range(MAX):
        ch = chr(cp)
        if 0xD800 <= cp <= 0xDFFF or not ch.isdecimal():
            continue
        v = unicodedata.decimal(ch)
        if out and out[-1][1] == cp - 1 and out[-1][2] + (cp - out[-1][0]) == v:
            out[-1] = (out[-1][0], cp, out[-1][2])
        else:
            out.append((cp, cp, v))
    return out


def is_emoji(ch: str) -> bool:  # glance.privacy.entities._is_emoji
    if ch == "￼":
        return False
    return 0x1F000 <= ord(ch) <= 0x1FAFF or unicodedata.category(ch) == "So"


def table(name: str, rs: list[tuple[int, int]]) -> str:
    body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}];\n"


def main() -> int:
    word = re.compile(r"\w")
    space = re.compile(r"\s")
    digit = re.compile(r"\d")
    parts = [
        "// @generated by scripts/gen-privacy-tables.py; do not edit.\n",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n\n",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n\n',
        "/// Python `re` `\\w` on str.\n",
        table("WORD", ranges(lambda c: word.match(c) is not None)),
        "/// Python `re` `\\s` on str.\n",
        table("SPACE", ranges(lambda c: space.match(c) is not None)),
        "/// `entities._is_emoji`.\n",
        table("EMOJI", ranges(is_emoji)),
        "/// Python `re` `\\d` on str: (first, last, decimal value of first).\n",
        "pub static DECIMAL: &[(u32, u32, u32)] = &[\n"
        + "".join(f"    (0x{a:X}, 0x{b:X}, {v}),\n" for a, b, v in decimal_runs()) + "];\n",
        "/// Python `re.IGNORECASE`: every code point each keyword letter matches.\n",
        "pub static IGNORECASE: &[(char, &[u32])] = &[\n",
    ]
    for letter in KEYWORD_LETTERS:
        rx = re.compile(letter, re.IGNORECASE)
        cps = [cp for cp in range(MAX) if not 0xD800 <= cp <= 0xDFFF and rx.fullmatch(chr(cp))]
        parts.append(f"    ('{letter}', &[{', '.join(f'0x{c:X}' for c in cps)}]),\n")
    parts.append("];\n")
    # every \d must be a decimal with a value (the card detector reads it)
    assert all(chr(c).isdecimal() for c in range(MAX)
               if not 0xD800 <= c <= 0xDFFF and digit.match(chr(c)))
    OUT.write_text("".join(parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
