"""MacClipboard: the write-back ClipboardPort over the general NSPasteboard.

`save` copies every item's every type (refused above 8 MB, as on Linux). `set_secret_text`
marks the text transient and concealed (the nspasteboard.org convention) so clipboard
managers skip it; macOS has no way to offer it to one application only. `restore` puts the
saved items back unless someone else wrote to the pasteboard in the meantime (their copy wins).

Needs PyObjC (AppKit); imported only on a Mac.
"""
from __future__ import annotations

from typing import Any

from AppKit import NSPasteboard, NSPasteboardItem
from Foundation import NSData

from glance.log import log_event
from glance.writeback.ports import ClipSnapshot

MAX_BYTES = 8 * 1024 * 1024
TEXT = "public.utf8-plain-text"
MARKS = ("org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
         "org.nspasteboard.AutoGeneratedType")


class MacClipboard:
    def __init__(self, pasteboard: Any = None) -> None:
        self._pb = pasteboard if pasteboard is not None else NSPasteboard.generalPasteboard()
        self._ours: int | None = None  # changeCount right after our own write

    def save(self) -> ClipSnapshot | None:
        items: list[list[tuple[str, bytes]]] = []
        total = 0
        for item in self._pb.pasteboardItems() or ():
            kept: list[tuple[str, bytes]] = []
            for t in item.types() or ():
                data = item.dataForType_(t)
                if data is None:
                    continue
                raw = bytes(data)
                total += len(raw)
                if total > MAX_BYTES:
                    log_event("clipboard_too_large")
                    return None
                kept.append((str(t), raw))
            items.append(kept)
        return ClipSnapshot(items)

    def set_secret_text(self, text: str, target_window: int) -> None:
        item = NSPasteboardItem.alloc().init()
        item.setString_forType_(text, TEXT)
        for mark in MARKS:
            item.setData_forType_(NSData.data(), mark)
        self._pb.clearContents()
        if not self._pb.writeObjects_([item]):
            raise OSError("pasteboard write failed")
        self._ours = int(self._pb.changeCount())

    def restore(self, snap: ClipSnapshot) -> None:
        if self._ours is not None and int(self._pb.changeCount()) != self._ours:
            log_event("clipboard_changed_by_other")  # the user copied something: keep it
            self._ours = None
            return
        self._ours = None
        self._pb.clearContents()
        items = []
        for kept in snap.payload:  # type: ignore[union-attr]
            item = NSPasteboardItem.alloc().init()
            for t, raw in kept:
                item.setData_forType_(NSData.dataWithBytes_length_(raw, len(raw)), t)
            items.append(item)
        if items and not self._pb.writeObjects_(items):
            raise OSError("pasteboard restore failed")

    def close(self) -> None:
        pass
